# Color definitions
[ -z "${_CLR_RESET+x}" ] && _CLR_RESET='\033[0m' 2>/dev/null || true
[ -z "${_CLR_BOLD+x}" ] && _CLR_BOLD='\033[1m' 2>/dev/null || true
[ -z "${_CLR_DIM+x}" ] && _CLR_DIM='\033[2m' 2>/dev/null || true
[ -z "${_CLR_INFO+x}" ] && _CLR_INFO='\033[38;5;87m' 2>/dev/null || true
[ -z "${_CLR_SUCCESS+x}" ] && _CLR_SUCCESS='\033[38;5;83m' 2>/dev/null || true
[ -z "${_CLR_WARN+x}" ] && _CLR_WARN='\033[38;5;221m' 2>/dev/null || true
[ -z "${_CLR_ERROR+x}" ] && _CLR_ERROR='\033[38;5;203m' 2>/dev/null || true
[ -z "${_CLR_ACCENT+x}" ] && _CLR_ACCENT='\033[38;5;177m' 2>/dev/null || true

